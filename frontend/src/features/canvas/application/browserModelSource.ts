// Where browser-side inference (matting, depth motion capture) fetches model weights and the onnxruntime wasm from.
//
// transformers.js by default fetches weights from the Hugging Face Hub and wasm from jsDelivr,
// which are largely unreachable from some networks. When the backend sets BROWSER_MODEL_ASSET_BASE,
// they are fetched from that prefix instead, with this directory layout:
//
//   <base>/models/<org>/<model>/{config.json,preprocessor_config.json,onnx/*.onnx}
//   <base>/onnxruntime-web/<version>/ort-wasm-simd-threaded[.asyncify].{mjs,wasm}
//
// The directory is generated by scripts/fetch_browser_models.py. The wasm directory carries the onnxruntime-web version:
// the wasm must match the version of the JS glue bundled into the build, so after a dependency upgrade
// an old directory must not be used by a newer frontend.
//
// If you do not want to self-host, you can instead point to public mirrors (each takes priority over the self-hosted prefix):
//   BROWSER_MODEL_HF_ENDPOINT  weights source, with the same path rules as the Hugging Face Hub
//                              (<endpoint>/<org>/<model>/resolve/<revision>/<file>)
//   BROWSER_ORT_WASM_BASE      wasm directory; `{version}` is replaced with the onnxruntime-web version
//
// The worker cannot read the main thread's runtime config, so the main thread passes these addresses in with the task message.

/** The three addresses delivered by the backend /api/v1/config, passed into the worker with the task message. */
export interface BrowserModelSourceConfig {
  /** Self-hosted prefix (BROWSER_MODEL_ASSET_BASE). */
  assetBase: string | null;
  /** Weights mirror following Hugging Face path rules (BROWSER_MODEL_HF_ENDPOINT). */
  hfEndpoint: string | null;
  /** onnxruntime wasm directory, may contain `{version}` (BROWSER_ORT_WASM_BASE). */
  ortWasmBase: string | null;
}

/** The two parts are independent: whichever is missing keeps the library's default source. */
export interface BrowserModelSource {
  /** Maps to transformers.js env.remoteHost / env.remotePathTemplate. */
  models?: { remoteHost: string; remotePathTemplate?: string };
  /** Maps to env.backends.onnx.wasm.wasmPaths. */
  wasmPaths?: { mjs: string; wasm: string };
}

function normalizeBase(value: string | null | undefined): string {
  return value?.trim().replace(/\/+$/, "") ?? "";
}

/** Returns null when nothing is configured: keep the library's default source. */
export function resolveBrowserModelSource(
  config: BrowserModelSourceConfig | null | undefined,
  ortWebVersion: string | null | undefined,
  isSafari: boolean,
): BrowserModelSource | null {
  const assetBase = normalizeBase(config?.assetBase);
  const hfEndpoint = normalizeBase(config?.hfEndpoint);
  const ortWasmBase = normalizeBase(config?.ortWasmBase);
  const source: BrowserModelSource = {};

  if (hfEndpoint) {
    // The mirror follows the Hub's path rules; only the host changes and remotePathTemplate keeps the library default.
    source.models = { remoteHost: `${hfEndpoint}/` };
  } else if (assetBase) {
    source.models = { remoteHost: `${assetBase}/models/`, remotePathTemplate: "{model}/" };
  }

  // The wasm must match the bundled JS glue version; without a version number the directory cannot be built, so keep the library default.
  if (ortWebVersion) {
    const wasmDir = ortWasmBase
      ? ortWasmBase.split("{version}").join(ortWebVersion)
      : assetBase
        ? `${assetBase}/onnxruntime-web/${ortWebVersion}`
        : "";
    if (wasmDir) {
      // Matches transformers.js's own choice: Safari uses the plain build, everything else the asyncify build.
      const stem = isSafari ? "ort-wasm-simd-threaded" : "ort-wasm-simd-threaded.asyncify";
      source.wasmPaths = { mjs: `${wasmDir}/${stem}.mjs`, wasm: `${wasmDir}/${stem}.wasm` };
    }
  }

  return source.models || source.wasmPaths ? source : null;
}

/**
 * Copied from transformers.js's isSafari so the selected wasm variant matches the library's default behavior.
 * Note that navigator in a worker usually has no vendor, in which case both the library and this code judge it as non-Safari.
 */
export function isSafariUserAgent(userAgent: string, vendor: string): boolean {
  const isAppleVendor = vendor.includes("Apple");
  const notOtherBrowser =
    !/CriOS|FxiOS|EdgiOS|OPiOS|mercury|brave/i.test(userAgent) &&
    !userAgent.includes("Chrome") &&
    !userAgent.includes("Android");
  return isAppleVendor && notOtherBrowser;
}

/** The part of the transformers.js env that this module writes. */
export interface TransformersEnvLike {
  remoteHost: string;
  remotePathTemplate: string;
  backends: {
    onnx: {
      versions?: { web?: string };
      wasm?: { wasmPaths?: unknown };
    };
  };
}

/** Call inside the worker, before creating the pipeline. Leaves env untouched when nothing is configured. */
export function applyBrowserModelSource(
  env: TransformersEnvLike,
  config: BrowserModelSourceConfig | null | undefined,
  navigatorLike: { userAgent?: string; vendor?: string },
): void {
  const onnx = env.backends.onnx;
  const source = resolveBrowserModelSource(
    config,
    onnx.versions?.web,
    isSafariUserAgent(navigatorLike.userAgent ?? "", navigatorLike.vendor ?? ""),
  );
  if (!source) {
    return;
  }
  if (source.models) {
    env.remoteHost = source.models.remoteHost;
    if (source.models.remotePathTemplate) {
      env.remotePathTemplate = source.models.remotePathTemplate;
    }
  }
  if (source.wasmPaths && onnx.wasm) {
    onnx.wasm.wasmPaths = source.wasmPaths;
  }
}
